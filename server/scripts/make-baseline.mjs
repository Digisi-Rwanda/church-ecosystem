// Writes prisma/migrations/0001_baseline from the current Postgres schema.
// Run once, from server/:  npm run db:baseline   (needs no database connection)
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join('prisma', 'migrations', '0001_baseline');
if (existsSync(dir)) {
  console.error(`${dir} already exists. Nothing written.`);
  process.exit(1);
}
const r = spawnSync(
  'npx',
  ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.postgres.prisma', '--script'],
  { encoding: 'utf8', shell: true },
);
if (r.status !== 0 || !r.stdout.trim()) {
  console.error(r.stderr || 'prisma migrate diff produced nothing');
  process.exit(r.status || 1);
}
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'migration.sql'), r.stdout);
writeFileSync(
  join('prisma', 'migrations', 'migration_lock.toml'),
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
);
console.log(`Wrote ${join(dir, 'migration.sql')} (${r.stdout.split('\n').length} lines).`);
